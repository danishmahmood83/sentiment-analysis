CREATE TABLE tracked_symbols (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR2(10) NOT NULL,
    name VARCHAR2(255),
    exchange VARCHAR2(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE tracked_symbols ADD CONSTRAINT uq_symbol UNIQUE (symbol);



CREATE TABLE STOCK_SENTIMENT
   (	"ID" NUMBER GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE,
	"SYMBOL" VARCHAR2(255 CHAR),
	"MESSAGE" CLOB,
	"SENTIMENT" VARCHAR2(255 CHAR),
	"CREATED_AT" TIMESTAMP (6),
	 PRIMARY KEY ("ID")
